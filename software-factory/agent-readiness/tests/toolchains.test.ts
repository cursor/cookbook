const rubric = loadRubric("2026-11-alpha");

function tree(files: Record<string, string>, opts: { git?: boolean } = {}): string {
  const dir = join(mkdtempSync(join(tmpdir(), "readiness-toolchains-")), "repo");
  for (const [rel, text] of Object.entries(files)) {
    mkdirSync(join(dir, rel, ".."), { recursive: true });
    writeFileSync(join(dir, rel), text);
  }
  if (opts.git) {
    execFileSync("git", ["init", "-q", "-b", "main"], { cwd: dir });
    execFileSync("git", ["add", "-A"], { cwd: dir });
    execFileSync("git", ["-c", "commit.gpgsign=false", "-c", "user.name=Contributor A", "-c", "user.email=a@example.com", "commit", "-q", "-m", "initial"], { cwd: dir });
  }
  return dir;
}

function contractOf(files: Record<string, string>) {
  const dir = tree(files);
  const profile = buildProfile(dir, dir, rubric);
  return { dir, profile, contract: discoverContract(profile, dir, rubric, []) };
}

const command = (contract: ContractCommand[], id: string) => contract.find((c) => c.id === id)?.command;
const poetryLock = (version: string) => `# This file is automatically @generated by Poetry ${version} and should not be changed by hand.\npackage = []\n`;

describe("Poetry, Bun, Yarn 2 or later and uv workspaces are supported", () => {
  test("Poetry runs the frozen install of the Poetry that wrote the lock, into .venv", () => {
    const v1 = contractOf({ "pyproject.toml": "[tool.poetry]\nname = \"cleo\"\n\n[tool.poetry.group.dev.dependencies]\npytest = \"^8\"\n", "poetry.lock": poetryLock("1.8.3"), "cleo/__init__.py": "", "tests/test_a.py": "" });
    assert.deepEqual([v1.profile.components[0].stack, v1.profile.components[0].assessed], ["poetry", true]);
    assert.equal(command(v1.contract, "cmd-repo-install"), "POETRY_VIRTUALENVS_IN_PROJECT=true poetry install --sync --no-interaction -v");
    assert.equal(command(v1.contract, "cmd-cleo-test"), ".venv/bin/python -m pytest -q");
    assert.deepEqual(toolSetup(v1.profile, v1.dir).map((t) => t.spec), ["poetry==1.8.3"]);
    assert.equal(containerImage(v1.profile, v1.dir), "python:3.12-slim");
    const v2 = contractOf({ "pyproject.toml": "[project]\nname = \"cleo\"\n\n[tool.poetry]\nrequires-poetry = \">=2.0\"\n", "poetry.lock": poetryLock("2.2.1"), "cleo/__init__.py": "" });
    assert.equal(command(v2.contract, "cmd-repo-install"), "POETRY_VIRTUALENVS_IN_PROJECT=true poetry sync --no-interaction -v");
    assert.deepEqual(toolSetup(v2.profile, v2.dir).map((t) => t.spec), ["poetry==2.2.1"]);
    const unlocked = contractOf({ "pyproject.toml": "[tool.poetry]\nname = \"cleo\"\n", "cleo/__init__.py": "" });
    assert.equal(command(unlocked.contract, "cmd-repo-install"), "POETRY_VIRTUALENVS_IN_PROJECT=true poetry install --no-interaction -v");
    assert.match(unlocked.contract.find((c) => c.id === "cmd-repo-install")!.reason, /can't be frozen/);
  });

  test("Bun runs a frozen bun install, and the audit adds the pinned Bun to its Node image", () => {
    const pinned = contractOf({ "package.json": JSON.stringify({ name: "elysia", packageManager: "bun@1.2.19", scripts: { test: "bun test", build: "bun build.ts" } }), "bun.lock": "{}", "src/a.ts": "" });
    assert.deepEqual([pinned.profile.components[0].stack, pinned.profile.components[0].assessed], ["bun", true]);
    assert.equal(command(pinned.contract, "cmd-repo-install"), "bun install --frozen-lockfile");
    assert.equal(command(pinned.contract, "cmd-elysia-test"), "bun run test");
    assert.equal(command(pinned.contract, "cmd-repo-doctor"), "bun --version");
    assert.deepEqual(toolSetup(pinned.profile, pinned.dir).map((t) => t.spec), ["bun@1.2.19"]);
    assert.match(containerImage(pinned.profile, pinned.dir), /^node:\d+-bookworm$/);
    assert.deepEqual(pinned.profile.toolchain.files, ["package.json packageManager"], "the Bun pin is the toolchain pin");
    assert.deepEqual(pinned.profile.lockfiles, ["bun.lock"], "the frozen install has to reproduce bun.lock");
    const loose = contractOf({ "package.json": JSON.stringify({ name: "elysia", scripts: { test: "bun test" } }), "bun.lockb": "", "src/a.ts": "" });
    assert.deepEqual(toolSetup(loose.profile, loose.dir).map((t) => t.spec), ["bun@1"]);
    assert.deepEqual(loose.profile.toolchain.missing, ["the Bun version (packageManager or engines.bun in package.json)"]);
  });

  test("Yarn 2 or later runs an immutable install, pinned by packageManager or yarnPath", () => {
    const berry = { "package.json": JSON.stringify({ name: "medusa", packageManager: "yarn@4.5.0", scripts: { test: "jest" } }), "yarn.lock": "__metadata:\n  version: 8\n", ".nvmrc": "22\n" };
    const pinned = contractOf(berry);
    assert.deepEqual([pinned.profile.components[0].stack, pinned.profile.components[0].assessed], ["yarn-berry", true]);
    assert.equal(command(pinned.contract, "cmd-repo-install"), "corepack yarn install --immutable");
    const hooked = buildProfile(pinned.dir, pinned.dir, rubric);
    const network = discoverContract(hooked, pinned.dir, rubric, [{ id: "saf-001", kind: "network_piped", file: "package.json", detail: "x", blocking: true }]);
    assert.equal(command(network, "cmd-repo-install"), "corepack yarn install --immutable --mode=skip-build", "Berry skips build scripts with --mode, not --ignore-scripts");
    const viaPath = contractOf({ ...berry, "package.json": JSON.stringify({ name: "medusa", scripts: { test: "jest" } }), ".yarnrc.yml": "yarnPath: .yarn/releases/yarn-3.2.1.cjs\n" });
    assert.deepEqual([viaPath.profile.components[0].stack, viaPath.profile.toolchain.pinned], ["yarn-berry", true]);
    assert.ok(viaPath.profile.toolchain.files.includes(".yarnrc.yml yarnPath"));
  });

  test("Yarn 2 or later with no pin isn't supported yet, because Corepack would run Yarn 1", () => {
    const { profile } = contractOf({ "package.json": JSON.stringify({ name: "medusa", scripts: { test: "jest" } }), "yarn.lock": "__metadata:\n  version: 8\n" });
    assert.equal(profile.components[0].assessed, false);
    assert.equal(profile.components[0].notAssessedReason, "Yarn 2 or later with no version pin isn't supported yet: nothing says which Yarn to run: add packageManager to package.json or yarnPath to .yarnrc.yml");
  });

  test("a uv workspace's members are components, installed together from the root uv.lock with their test groups", () => {
    const files = {
      "pyproject.toml": "[tool.uv.workspace]\nmembers = [\"packages/*\", \"backend\"]\nexclude = [\"packages/legacy\"]\n\n[tool.ruff]\nline-length = 100\n",
      "uv.lock": "version = 1\n",
      ".python-version": "3.12\n",
      "backend/pyproject.toml": "[project]\nname = \"app-backend\"\n\n[dependency-groups]\ndev = [\"pytest>=8\"]\n",
      "backend/app/main.py": "",
      "packages/sdk/pyproject.toml": "[project]\nname = \"sdk\"\n\n[dependency-groups]\ntest = [\"pytest\"]\ndocs = [\"sphinx\"]\n",
      "packages/sdk/sdk/__init__.py": "",
      "packages/sdk/tests/test_sdk.py": "",
      "packages/legacy/pyproject.toml": "[project]\nname = \"legacy\"\n",
    };
    const { dir, profile, contract } = contractOf(files);
    assert.deepEqual(uvWorkspaceMembers(dir), ["backend", "packages/sdk"]);
    assert.deepEqual(profile.components.map((c) => [c.id, c.path, c.stack]), [["app-backend", "backend", "uv-workspace"], ["sdk", "packages/sdk", "uv-workspace"], ["legacy", "packages/legacy", "pip"]], "the virtual root isn't a component, and an excluded folder is its own project");
    assert.deepEqual(testGroups(dir, [".", "backend", "packages/sdk"]), ["test"]);
    assert.equal(command(contract, "cmd-repo-install"), "uv sync --frozen --all-packages --group test");
    assert.deepEqual(contract.filter((c) => c.kind === "install").map((c) => c.cwd), [".", "packages/legacy"], "one install for the whole workspace");
    assert.equal(command(contract, "cmd-app-backend-test"), "../.venv/bin/python -m pytest -q");
    assert.equal(command(contract, "cmd-sdk-test"), "../../.venv/bin/python -m pytest -q");
    assert.match(containerImage(profile, dir), /^ghcr\.io\/astral-sh\/uv:python3\.12-/);
    const rooted = contractOf({ ...files, "pyproject.toml": "[project]\nname = \"monolith\"\n\n[tool.uv.workspace]\nmembers = [\"backend\"]\n", "monolith/__init__.py": "" });
    assert.deepEqual(rooted.profile.components.map((c) => c.id), ["monolith", "app-backend"], "a root with its own [project] is a member too");
  });

  test("bun test's totals are read like the other runners'", () => {
    assert.deepEqual(testCounts("test/a.test.js:\n(pass) a\n(fail) b\n\n 4 pass\n 1 fail\n 9 expect() calls\nRan 5 tests across 2 files. [12.00ms]\n"), { passed: 4, failed: 1, total: 5 });
  });
});

function timingExecutor(durationSec: (command: string) => number): Executor & { ran: { command: string; timeoutSec: number }[] } {
  const ran: { command: string; timeoutSec: number }[] = [];
  const ex = {
    where: "container" as const,
    strength: "clean_replay" as const,
    image: "node:22-bookworm",
    imageSource: "audit" as const,
    root: mkdtempSync(join(tmpdir(), "readiness-toolchains-")),
    ran,
    exec: async (cmdText: string, _cwd: string, timeoutSec: number) => {
      ran.push({ command: cmdText, timeoutSec });
      const want = durationSec(cmdText);
      const timedOut = want > timeoutSec;
      return { timedOut, durationMs: Math.min(want, timeoutSec) * 1000, output: timedOut ? "" : "ok", exitCode: timedOut ? null : 0 };
    },
    offline: () => (ex.networkOff = true),
    networkOff: null as boolean | null,
    close: () => {},
  };
  return ex;
}

const cmd = (id: string, kind: ContractCommand["kind"], component = "app", timeoutSec = 600): ContractCommand => ({ id, kind, component, cwd: ".", command: id, source: "readiness", reason: kind, timeoutSec });

describe("time bounds on large repos", () => {
  test("no command runs longer than the budget left, and one the budget cuts off is blocked, not failed", async () => {
    const budget = newBudget(15, 2);
    budget.startedAt = Date.now() - 90000;
    const ex = timingExecutor(() => 120);
    const results = await runContract(ex, [cmd("install", "install", "*"), cmd("test", "test")], { components: new Set(["app"]), budget, registryValues: [] });
    assert.ok(ex.ran[0].timeoutSec <= 30, `the install got ${ex.ran[0].timeoutSec}s of a 2-minute budget with 90s used`);
    assert.deepEqual(results.map((r) => [r.cmd.id, r.status, r.blocked]), [["install", "not_run", BUDGET_OUT], ["test", "not_run", "the install was blocked on this machine"]]);
  });

  test("a component's own budget caps its commands", () => {
    const budget = newBudget(1, 60);
    budget.used.set("app", 45000);
    assert.ok(budgetLeftSec(budget, "app") <= 15);
    assert.ok(budgetLeftSec(budget, "*") > 3000);
  });

  test("an install that outlasts its own limit is blocked as this machine's limit", () => {
    const d = { cause: "timeout" as const, detail: "the install step ran out of time" };
    assert.equal(environmentLimit({ where: "container", image: "node:22-bookworm", imageSource: "audit" }, cmd("i", "install", "*", 600), d, []), "the install ran past the audit's 10-minute limit on this machine");
    assert.equal(environmentLimit({ where: "container", image: "node:22-bookworm", imageSource: "audit" }, cmd("t", "test"), { ...d, detail: "the test step ran out of time" }, []), undefined, "a test that hangs is still the repo's");
  });

  test("past the scan's bound the secret scan and asset history stop, and say how far they got", () => {
    const files: Record<string, string> = { "package.json": "{\"name\":\"big\"}", "AGENTS.md": "# Agents\n", "packages/a/AGENTS.md": "# A\n" };
    for (let i = 0; i < 50; i++) files[`src/file-${i}.js`] = `export const n${i} = ${i};\n`;
    const dir = tree(files, { git: true });
    const profile = buildProfile(dir, dir, rubric);
    const bound: ScanBound = { until: Date.now() - 1, scope: { boundMinutes: 3, files: 0, fileCap: null, secrets: { scanned: 0, total: 0 }, assetHistory: { read: 0, total: 0 } } };
    safetyScan(dir, profile, bound);
    const assets = inventory(dir, dir, [], bound);
    assert.deepEqual(bound.scope.secrets, { scanned: 0, total: 53 });
    assert.deepEqual(bound.scope.assetHistory, { read: 0, total: 2 });
    assert.deepEqual(assets.map((a) => [a.path, a.authors]), [["AGENTS.md", []], ["packages/a/AGENTS.md", []]], "assets are still listed and checked");
    const open: ScanBound = { until: Date.now() + 60000, scope: { ...bound.scope, secrets: { scanned: 0, total: 0 }, assetHistory: { read: 0, total: 0 } } };
    safetyScan(dir, profile, open);
    assert.equal(inventory(dir, dir, [], open)[0].authors[0]?.name, "Contributor A");
    assert.deepEqual([open.scope.secrets.scanned, open.scope.assetHistory.read], [53, 2]);
  });

  test("the coverage line states the sampled scope", () => {
    const audit = makeAudit({ components: [{ id: "app", share: 1, faults: "pass" }] });
    assert.doesNotMatch(reportFor(audit).executive.coverage, /Sampled scope/);
    audit.profile!.scope = { boundMinutes: 3, files: 24654, fileCap: null, secrets: { scanned: 12000, total: 24654 }, assetHistory: { read: 43, total: 180 } };
    audit.evidence.push({ id: "ev-099", at: audit.createdAt, checkId: "bootstrap.cold_replay", condition: "clean.build", component: "app", kind: "build", strength: "clean_replay", where: "container", result: "not_run", summary: "build not run: cut off by the time budget", blocked: BUDGET_OUT });
    assert.equal(sampledScope(audit), "the secret scan read 12,000 of 24,654 files before the scan's 3-minute bound; git history was read for 43 of 180 agent assets; the time budget cut off 1 command");
    assert.match(reportFor(audit).executive.coverage, /Sampled scope: the secret scan read 12,000 of 24,654 files/);
    audit.profile!.scope.fileCap = 50000;
    audit.evidence.push({ id: "ev-100", at: audit.createdAt, checkId: "verify.behavioral_oracle", condition: "faults", component: "app", strength: "clean_replay", where: "container", result: "pass", summary: "caught 4 of 4 planted faults (tried: boundary_flip); the time budget cut off 1 of 5" });
    audit.instructions = [{ id: "ins-001", source: "AGENTS.md", line: 1, kind: "command", text: "npm test", category: "replay", staticResult: "pass", result: "not_run", reason: CUT_OFF }];
    const all = sampledScope(audit)!;
    assert.match(all, /^the scan listed only the first 50,000 files; .*planted faults in app stopped at the time budget; 1 documented command wasn't run before the time budget ran out$/);
    for (const term of rubric.part1.bannedTerms) assert.ok(!all.toLowerCase().includes(term.toLowerCase()), `the sampled scope can't say "${term}" in part 1`);
  });

  test("scan --budget-scan samples a large tree, finishes, and says what it sampled", () => {
    const files: Record<string, string> = { "package.json": JSON.stringify({ name: "big", scripts: { test: "node --test" } }), "package-lock.json": "{}", ".nvmrc": "22\n" };
    for (let i = 0; i < 3000; i++) files[`packages/p${i % 30}/src/f${i}.js`] = `export const n = ${i};\n`;
    const dir = tree(files, { git: true });
    assert.equal(readiness(dir, ["init", "--tier", "read-only"]).code, 0);
    const started = Date.now();
    const scan = readiness(dir, ["scan", "--budget-scan", "0.0001"]);
    assert.equal(scan.code, 0, scan.out);
    assert.ok(Date.now() - started < 60000);
    assert.match(scan.out, /Sampled: the secret scan read \d[\d,]* of 3,003 files before the scan's 0\.0001-minute bound/);
    assert.match(readiness(dir, ["scan", "--budget-scan", "0"]).out, /--budget-scan takes the scan's time bound in minutes/);
  });
});
